"""Create tiny parquet files with the AIDev v5 schema, for testing the pipeline
offline. Contents are random and carry no information about real projects."""
import random, sys
from pathlib import Path
import pandas as pd

out = Path(sys.argv[1] if len(sys.argv) > 1 else "fake_aidev"); out.mkdir(parents=True, exist_ok=True)
rng = random.Random(0)
agents = ["Claude_Code", "Codex", "Copilot", "Cursor", "Devin"]
prs, commits = [], []
pid = 0
for r in range(12):
    repo = f"https://github.com/org{r}/repo{r}"
    for n in range(rng.randint(3, 8)):
        pid += 1
        agent = rng.choice(agents)
        title = rng.choice(["Add CRUD routes", "Implement SQLAlchemy model for users", "Fix bug", "Add pytest fixture for db"])
        prs.append(dict(id=pid, number=n, agent=agent, user=f"{agent}[bot]", state="closed",
                        created_at="2026-01-10T00:00:00Z", closed_at="2026-01-11T00:00:00Z",
                        merged_at=None if rng.random() < 0.2 else "2026-01-11T00:00:00Z",
                        repo_url=repo, title=title, body="Generated by agent. " + title))
        for f in range(rng.randint(1, 3)):
            lines = ["+import os", "+from sqlalchemy import Column", "+", "+# comment",
                     "+def handler(x):", "+    return x + 1", "+    y = x * 2", "+    return y"]
            patch = "@@ -1,2 +1,8 @@\n" + "\n".join(rng.sample(lines, len(lines)))
            commits.append(dict(pr_id=pid, sha=f"sha{pid}{f}", filename=rng.choice([f"src/m{f}.py", "README.md"]),
                                status="modified", patch=patch))
pd.DataFrame(prs).to_parquet(out / "pull_request.parquet", index=False)
pd.DataFrame(commits).to_parquet(out / "pr_commit_details.parquet", index=False)
print("wrote", len(prs), "PRs and", len(commits), "file changes to", out)
